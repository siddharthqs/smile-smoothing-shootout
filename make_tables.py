def rcsv(path, **kw):
    """Read a released CSV, plain or gzipped."""
    if not os.path.exists(path) and os.path.exists(path + '.gz'):
        path += '.gz'
    return pd.read_csv(path, **kw)
def tobool(s):
    return s.map(lambda v: BOOL.get(v, np.nan))
def med(s):
    s = pd.Series(s).dropna().astype(float)
    return np.nan if len(s) == 0 else float(np.median(s))
def pc(s, p):
    s = pd.Series(s).dropna().astype(float)
    return np.nan if len(s) == 0 else float(np.percentile(s, p))
def f(x, d=2):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '--'
    return f'{x:,.{d}f}'.replace(',', r'\,')
def i(x):
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return '--'
    return f'{int(x):,}'.replace(',', r'\,')
def n_(k, frame):
    """A count, or '--' when its source frame is empty (intraday CSVs absent)."""
    return '--' if len(frame) == 0 else i(k)

