def spread_over(b, models):
    x = b[b.model.isin(models)]
    key = ['ticker', 'date', 'time', 'maturity', 'prod', 'bm']
    g = (x.groupby(key, dropna=False)
           .agg(n=('pv', 'size'), mn=('pv', 'min'), mx=('pv', 'max'), mean=('pv', 'mean'),
                se=('std_err', 'mean'), spot=('spot', 'first'),
                below=('below', 'max'), beyond=('beyond', 'max')).reset_index())
    g = g[g.n == len(models)].copy()
    g['rel'] = (g.mx - g.mn) / g['mean'] * 100
    g['absbp'] = (g.mx - g.mn) / g.spot * 1e4
    g['sig'] = (g.mx - g.mn) / g.se
    g['pricebp'] = g['mean'] / g.spot * 1e4
    g['sebp'] = g.se / g.spot * 1e4
    return g

def pair_gap(b, m1, m2):
    key = ['ticker', 'date', 'time', 'maturity', 'prod', 'bm']
    p1 = b[b.model == m1].set_index(key)[['pv', 'spot', 'se_' if False else 'std_err', 'below', 'beyond']]
    p2 = b[b.model == m2].set_index(key)[['pv']]
    j = p1.join(p2, rsuffix='_2', how='inner').reset_index()
    j['rel'] = (j.pv - j.pv_2).abs() / ((j.pv + j.pv_2) / 2) * 100
    j['absbp'] = (j.pv - j.pv_2).abs() / j.spot * 1e4
    j['sig'] = (j.pv - j.pv_2).abs() / j.std_err
    return j

